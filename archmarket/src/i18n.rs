use std::sync::OnceLock;

pub fn ru() -> bool {
    static RU: OnceLock<bool> = OnceLock::new();
    *RU.get_or_init(|| {
        ["LC_ALL", "LC_MESSAGES", "LANG"]
            .iter()
            .find_map(|k| std::env::var(k).ok().filter(|v| !v.is_empty()))
            .map(|v| v.starts_with("ru"))
            .unwrap_or(false)
    })
}

